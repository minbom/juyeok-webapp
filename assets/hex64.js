/* 하괘·상괘로 괘를 찾는다 */
function lookupHex(upper, lower) {
  for (const n in HEX64) if (HEX64[n][1] === upper && HEX64[n][2] === lower) return { num: +n, name: HEX64[n][0] };
  return null;
}
/* 효값 6개(초효부터) → { 본괘, 지괘, 변효자리 } */
function readCast(values) {
  const yang = (v) => v === 7 || v === 9;
  const moved = (v) => (v === 9 ? 8 : v === 6 ? 7 : v);
  const tri = (vs) => TRI_ORDER.find((t) => TRIGRAMS[t].bits === vs.map((v) => (yang(v) ? "1" : "0")).join(""));
  const of = (vs) => lookupHex(tri(vs.slice(3, 6)), tri(vs.slice(0, 3)));
  const changed = values.map(moved);
  return {
    ben: of(values),
    zhi: of(changed),
    movingAt: values.map((v, i) => (v === 6 || v === 9 ? i + 1 : null)).filter(Boolean),
  };
}
